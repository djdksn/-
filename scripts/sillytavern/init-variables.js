/**
 * Seed lorebook entries into IndexedDB if they don't already exist.
 * Call once after store.loadAll().
 */
export async function seedLorebooksIfNeeded(store) {
  const existingIds = new Set(store.lorebooks.map(b => b.id));
  const seeds = getSeedLorebooks();
  let added = 0;

  for (const seed of seeds) {
    if (!existingIds.has(seed.id)) {
      await store._db.table('lorebooks').put({
        ...seed,
        key: [], keysecondary: [], triggers: [],
        scanDepth: null, vectorized: false,
        selectiveLogic: 0, excludeRecursion: false, preventRecursion: false,
        sticky: null, cooldown: null, delay: null,
        group: '', groupOverride: false, groupWeight: 100,
        caseSensitive: null, matchWholeWords: null, useGroupScoring: null,
        automationId: '', outletName: '',
        matchPersonaDescription: false, matchCharacterDescription: false,
        matchCharacterPersonality: false, matchCharacterDepthPrompt: false,
        matchScenario: false, matchCreatorNotes: false,
        characterFilter: { isExclude: false, names: [], tags: [] },
        addMemo: true, ignoreBudget: false,
        createdAt: Date.now(), updatedAt: Date.now(),
      });
      store.lorebooks = [...store.lorebooks, seed];
      added++;
    }
  }

  if (added > 0) {
    // Auto-activate the new lorebooks
    const activeIds = new Set(store.settings?.activeLorebookIds || []);
    for (const seed of seeds) {
      if (!activeIds.has(seed.id)) activeIds.add(seed.id);
    }
    await store.updateSettings({ activeLorebookIds: Array.from(activeIds) });
    console.log('[init-variables] Seeded %d lorebook entries', added);
  }
}

/**
 * Inject initial variables into a chat's variable store.
 * Creates the variables in both chat.variables (for persistence) and
 * variableStore (for macro expansion).
 */
export function injectVariablesIntoChat(store, chatId) {
  const chat = store.chats.find(c => c.id === chatId);
  if (!chat) { console.error('[init-variables] Chat not found:', chatId); return; }

  const initial = getInitialChatVariables();
  const merged = deepMerge(initial, chat.variables || {});
  const updated = { ...chat, variables: merged, updatedAt: Date.now() };
  store._db.table('chats').put(updated);
  store.chats = store.chats.map(c => c.id === updated.id ? updated : c);

  // Also load into variableStore for immediate macro access
  for (const [key, value] of Object.entries(merged)) {
    variableStore.setVarSync(key, value, null, { id: updated.id, variables: merged }, 'system-init');
  }

  store._notify();
  console.log('[init-variables] Variables injected into chat:', chatId);
}

function deepMerge(base, override) {
  const result = { ...base };
  for (const key of Object.keys(override)) {
    if (override[key] && typeof override[key] === 'object' && !Array.isArray(override[key])
        && base[key] && typeof base[key] === 'object') {
      result[key] = deepMerge(base[key], override[key]);
    } else {
      result[key] = override[key];
    }
  }
  return result;
}
