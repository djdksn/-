function buildSchemas() {
  const r = {};

  // ── User info: numeric fields ──────────────────────────────
  const userNums = [
    'User信息.性交总次数', 'User信息.接受性交次数', 'User信息.接受口交次数',
    'User信息.接受肛交次数', 'User信息.接受色情按摩次数', 'User信息.发生性关系总人数',
    'User信息.年龄',
  ];
  for (const f of userNums) r[f] = { type: 'number', min: 0 };

  // ── User info: string fields ───────────────────────────────
  for (const f of ['User信息.姓名', 'User信息.所属部门', 'User信息.职务']) {
    r[f] = { type: 'string' };
  }

  // ── NPC roster (wildcard) ─────────────────────────────────
  const npc = 'NPC花名册.*';

  r[`${npc}.动态数据.人物好感度`] = {
    type: 'string', enum: ['厌恶', '一般', '友善', '爱慕'],
  };

  const npcNums = ['性行为次数', '性交次数', '口交次数', '肛交次数', '足交次数'];
  for (const f of npcNums) {
    r[`${npc}.动态数据.经历.${f}`] = { type: 'number', min: 0 };
  }

  r[`${npc}.静态数据.社会情况.年龄`] = { type: 'number', min: 1, max: 120 };

  const bodyParts = ['口', '腋', '胸', '腹', '下体', '臀', '腿', '足'];
  for (const p of bodyParts) {
    r[`${npc}.动态数据.身体状态.即时痕迹.${p}`] = { type: 'string' };
  }
  r[`${npc}.动态数据.身体状态.整体反馈`] = { type: 'string' };
  for (const f of ['上衣', '下衣', '鞋', '袜', '配饰']) {
    r[`${npc}.动态数据.人物穿着.${f}`] = { type: 'string' };
  }
  r[`${npc}.动态数据.内心想法`] = { type: 'string' };

  // ── Courses (wildcard) ────────────────────────────────────
  r['课程.*.动态数据.课程进展'] = { type: 'string', enum: ['未开始', '进行中', '已完成'] };

  // ── Misc ──────────────────────────────────────────────────
  r['当前地点'] = { type: 'string' };
  r['当前时间.日期'] = { type: 'string' };
  r['当前时间.时间'] = { type: 'string' };

  return r;
}

